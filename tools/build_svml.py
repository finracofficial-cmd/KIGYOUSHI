#!/usr/bin/env python3
"""Generate the Hypit sources for an episode, one part per chapter.

A 20-25 minute film is rendered in parts (opening + title card, then one part per chapter, the last
part with the source roll and end card) because Hypit keeps a whole film's caption render in one
string, which exceeds JavaScript's string limit for long films. tools/run_episode.sh renders the
parts, joins them and lays the background music under the whole film.

Expects these prepared assets (see tools/prepare_assets.py):
  assets/derived/img/<image-id>.jpg, ident.jpg, credits.jpg
  assets/narration/<segment-id>.m4a  loudness-normalized narration per segment

Writes episode-pNN.svml / episode-pNN.svrun and out/parts.json.
Usage: build_svml.py <slug>
"""
from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

from PIL import Image

from episode_lib import CHANNEL, credits_duration, episode_dir, load_episode, script_prose, xml_escape

IMPORTS = [
    '<import from="@hypit/script@1"/>',
    '<import as="asset" from="@hypit/media@1"/>',
    '<import as="mediaop" from="@hypit/media-operations@1"/>',
    '<import as="whisperx" from="@hypit/whisperx@1"/>',
    '<import as="semantic" from="@hypit/narrative-temporal@1"/>',
    '<import as="narrative-caption" from="@hypit/narrative-caption@1"/>',
    '<import as="time" from="@hypit/timeline-author@1"/>',
    '<import as="visual" from="@hypit/visual-track@1"/>',
    '<import as="audio" from="@hypit/audio-track@1"/>',
    '<import as="caption-fine" from="@hypit/caption-fine@1"/>',
    '<import as="text" from="@hypit/text-fine@1"/>',
    '<import as="fonts" from="@hypit/fontsource@1"/>',
    '<import as="space" from="@hypit/spatial@1"/>',
    '<import as="film" from="@hypit/film@1"/>',
    '<import as="html" from="@hypit/html-video@1"/>',
    '<import as="look" source="../../channel/look.svs"/>',
]

FRAMES = {
    "full": (0, 0, 100, 100),
    "theme-main-frame": (1.6, 2.2, 75, 8.6),
    "theme-sub-frame": (1.6, 8.9, 75, 13.6),
    "logo-frame": (91.6, 2.2, 98.6, 14.6),
    "logo-sub-frame": (90.0, 14.8, 100.0, 17.4),
    "card-number-frame": (10, 33, 90, 44),
    "card-title-frame": (6, 45, 94, 62),
    "ident-logo-frame": (40, 22, 60, 57),
    "ident-title-frame": (6, 62, 94, 74),
    "ident-sub-frame": (6, 74, 94, 82),
    "credits-frame": (14, 0, 86, 100),
    "ending-frame": (10, 30, 90, 70),
}


def plan_parts(ep: dict) -> list[dict]:
    segs = ep["segments"]
    parts, rest = [], list(segs)
    if rest and rest[0].get("kind") == "opening":
        parts.append({"segs": [rest.pop(0)], "ident": True})
    for seg in rest:
        parts.append({"segs": [seg], "ident": not parts})
    if parts:
        parts[-1]["closing"] = True
    for i, p in enumerate(parts):
        p["name"] = f"p{i:02d}"
        p.setdefault("closing", False)
    return parts


def segment_hashes(ep: dict, d: Path) -> dict[str, str]:
    readings = ep.get("readings", {})
    hashes = {}
    for seg in ep["segments"]:
        h = hashlib.sha256((d / "assets" / "narration" / f"{seg['id']}.m4a").read_bytes())
        for b in seg["blocks"]:
            for line in b["lines"]:
                h.update(script_prose(line, readings).encode())
        hashes[seg["id"]] = h.hexdigest()
    return hashes


def render_part(ep: dict, d: Path, part: dict, chapter_no: dict[str, int]) -> str:
    ch = CHANNEL
    tm = ch["timing"]
    W, H, FPS = ch["canvas"]["width"], ch["canvas"]["height"], ch["canvas"]["fps"]
    xf = tm["crossfade_frames"]
    readings = ep.get("readings", {})
    segs = part["segs"]
    chapters = [s for s in segs if s.get("kind") == "chapter"]
    opening = next((s for s in segs if s.get("kind") == "opening"), None)
    credits = ep.get("credits") if part["closing"] else None
    closing = part["closing"]

    out: list[str] = []
    w = out.append
    w('<?svml using="@hypit/markup@1"?>')
    w(f"<!-- Generated by tools/build_svml.py from episode.json (part {part['name']}). Edit episode.json, not this file. -->")
    w("<svml>")
    for line in IMPORTS:
        w("  " + line)

    # ---- Script -------------------------------------------------------------------------------
    w('  <script id="story">')
    moments: dict[str, list[str]] = {}
    for seg in segs:
        sid = seg["id"]
        w(f"    <{sid}>")
        moments[sid] = []
        cue_lines = []
        for bi, block in enumerate(seg["blocks"]):
            for li, line in enumerate(block["lines"]):
                prose = script_prose(line, readings)
                if bi > 0 and li == 0:
                    mid = f"b-{sid}-{bi:02d}"
                    moments[sid].append(mid)
                    prose = f"@{{{mid}!}}" + prose
                cue_lines.append(prose)
        w(" ||\n".join("      " + c for c in cue_lines))
        w(f"    </{sid}>")
    w("  </script>")

    # ---- Assets -------------------------------------------------------------------------------
    used_images = []
    for seg in segs:
        for b in seg["blocks"]:
            if b["image"] not in used_images:
                used_images.append(b["image"])
    for img in used_images:
        w(f'  <asset:Image id="img-{img}" src="./assets/derived/img/{img}.jpg"/>')
    if part["ident"]:
        w('  <asset:Image id="img-ident" src="./assets/derived/ident.jpg"/>')
    if credits:
        w('  <asset:Image id="img-credits" src="./assets/derived/credits.jpg"/>')
    for seg in segs:
        w(f'  <asset:Audio id="narr-{seg["id"]}" src="./assets/narration/{seg["id"]}.m4a"/>')

    # ---- Space --------------------------------------------------------------------------------
    w(f'  <time:Clock id="clock" frame-rate="{FPS}"/>')
    w(f'  <space:Canvas id="canvas" width="{W}" height="{H}"/>')
    ext_sources = [(img, d / f"assets/derived/img/{img}.jpg") for img in used_images]
    if part["ident"]:
        ext_sources.append(("ident", d / "assets/derived/ident.jpg"))
    if credits:
        ext_sources.append(("credits", d / "assets/derived/credits.jpg"))
    for img, p in ext_sources:
        iw, ih = Image.open(p).size
        w(f'  <space:Extent id="ext-{img}" width="{iw}" height="{ih}"/>')
    for fid, (l, t, r, b) in FRAMES.items():
        w(f'  <space:Frame id="{fid}" within={{canvas.bounds}} left="{l}%" top="{t}%" right="{r}%" bottom="{b}%"/>')

    # ---- Media preparation and alignment ------------------------------------------------------
    for seg in segs:
        sid = seg["id"]
        w(f'  <mediaop:Normalize id="{sid}-media" source={{narr-{sid}}} video="none" audio="default" span-authority="audio" clock={{clock}}/>')
        w(f'  <whisperx:Alignment id="{sid}-align" narrative={{story}} segment={{story.segment.{sid}}} media={{{sid}-media.media}} domain={{{sid}-media.domain}} language="ja"/>')

    # ---- Timeline -----------------------------------------------------------------------------
    tail_ms = int(tm["chapter_tail_seconds"] * 1000)
    win_lines = []
    prev = "start"
    if opening:
        oid = opening["id"]
        win_lines += [f'<time:Window id="{oid}" from="start" for={{{oid}-media.extent}}/>',
                      f'<time:Window id="{oid}-tail" from="{oid}.end" for="800ms"/>',
                      f'<time:Window id="body-{oid}" from="{oid}.start" until="{oid}-tail.end"/>']
        prev = f"{oid}-tail.end"
    if part["ident"]:
        win_lines.append(f'<time:Window id="ident" from="{prev}" for="{tm["ident_seconds"]}s"/>')
        prev = "ident.end"
    for seg in chapters:
        sid = seg["id"]
        win_lines += [f'<time:Window id="card-{sid}" from="{prev}" for="{tm["card_seconds"]}s"/>',
                      f'<time:Window id="{sid}" from="card-{sid}.end" for={{{sid}-media.extent}}/>',
                      f'<time:Window id="{sid}-tail" from="{sid}.end" for="{tail_ms}ms"/>',
                      f'<time:Window id="body-{sid}" from="{sid}.start" until="{sid}-tail.end"/>']
        prev = f"{sid}-tail.end"
    if credits:
        win_lines.append(f'<time:Window id="credits" from="{prev}" for="{credits_duration(ep)}s"/>')
        prev = "credits.end"
    if closing:
        win_lines.append(f'<time:Window id="endcard" from="{prev}" for="{tm["end_card_seconds"]}s"/>')
        prev = "endcard.end"
    w(f'  <time:Timeline id="film" clock={{clock}} end="{prev}">')
    for line in win_lines:
        w("    " + line)
    w("  </time:Timeline>")

    # ---- Semantic projection ------------------------------------------------------------------
    w('  <semantic:Projection id="story-time" narrative={story} timeline={film.timeline}>')
    for seg in segs:
        sid = seg["id"]
        w(f'    <semantic:Map alignment={{{sid}-align.alignment}} domain={{{sid}-media.domain}} window={{film.{sid}}}/>')
    w("  </semantic:Projection>")

    # picture windows: each block's image holds until the next block's crossfade completes
    lead = xf * 2 // 3
    clips = []
    for seg in segs:
        sid = seg["id"]
        blocks = seg["blocks"]
        starts = [f"film.{sid}.start"]
        for mid in moments[sid]:
            w(f'  <semantic:Instant id="{mid}-at" projection={{story-time}} at={{story.moment.{mid}}}/>')
            w(f'  <time:Instant id="{mid}-in" timeline={{film.timeline}} at={{{mid}-at}} offset="-{lead}f"/>')
            w(f'  <time:Instant id="{mid}-done" timeline={{film.timeline}} at={{{mid}-at}} offset="+{xf - lead}f"/>')
            starts.append(f"{mid}-in")
        for bi, block in enumerate(blocks):
            win = f"show-{sid}-{bi:02d}"
            until = f"{moments[sid][bi]}-done" if bi < len(blocks) - 1 else f"film.{sid}-tail.end"
            w(f'  <time:Window id="{win}" timeline={{film.timeline}} from={{{starts[bi]}}} until={{{until}}}/>')
            clips.append((f"pic-{sid}-{bi:02d}", block["image"], win))

    w('  <visual:Motion id="fade-in">')
    w('    <visual:Pose at="start" opacity="0" easing="ease-in-out"/>')
    w(f'    <visual:Pose at="{xf}f" opacity="1"/>')
    w('    <visual:Pose at="end" opacity="1"/>')
    w("  </visual:Motion>")
    w('  <visual:Track id="picture" timeline={film.timeline}>')
    if part["ident"]:
        w('    <visual:Clip id="pic-ident" image={img-ident} extent={ext-ident} during={film.ident} frame={full} z="5" fit="cover" motion={fade-in}/>')
    for z, (cid, img, win) in enumerate(clips, start=10):
        w(f'    <visual:Clip id="{cid}" image={{img-{img}}} extent={{ext-{img}}} during={{{win}}} frame={{full}} z="{z}" fit="cover" motion={{fade-in}}/>')
    if credits:
        w('    <visual:Clip id="pic-credits" image={img-credits} extent={ext-credits} during={film.credits} frame={full} z="900" fit="cover" motion={fade-in}/>')
    w("  </visual:Track>")

    # ---- Sound (narration only; music is laid under the joined film) --------------------------
    w('  <audio:Track id="mix" timeline={film.timeline}>')
    for seg in segs:
        sid = seg["id"]
        w(f'    <audio:Clip id="voice-{sid}" source={{{sid}-media.media}} during={{film.{sid}}}/>')
    w("  </audio:Track>")

    # ---- Typography ---------------------------------------------------------------------------
    c = ch["colors"]
    w('  <fonts:Face id="jp-black" package="@fontsource-variable/noto-sans-jp" weight="900" style="normal"/>')
    w('  <fonts:Face id="jp-bold" package="@fontsource-variable/noto-sans-jp" weight="700" style="normal"/>')
    styles = {
        "theme-main-style": ("theme-main", "jp-black", f'<text:Fill color="{c["theme_main_text"]}"/><text:Box target="line" color="{c["theme_main_box"]}E6" padding="6 18" radius="0" border-color="{c["theme_accent"]}" border-width="0 0 0 8"/>'),
        "theme-sub-style": ("theme-sub", "jp-bold", f'<text:Fill color="{c["theme_sub_text"]}"/><text:Box target="line" color="{c["theme_sub_box"]}" padding="5 16" radius="0"/>'),
        "logo-style": ("logo", "jp-black", f'<text:Fill color="#FFFFFF"/><text:Box target="content" color="{c["seal"]}" padding="10 12" radius="6" border-color="#FFFFFF" border-width="3"/>'),
        "logo-sub-style": ("logo-sub", "jp-bold", '<text:Stroke color="#000000" width="3" placement="outside"/><text:Fill color="#FFFFFF"/>'),
        "ident-logo-style": ("ident-logo", "jp-black", f'<text:Fill color="#FFFFFF"/><text:Box target="content" color="{c["seal"]}" padding="26 30" radius="14" border-color="#FFFFFF" border-width="6"/>'),
        "ident-title-style": ("ident-title", "jp-black", '<text:Stroke color="#000000" width="8" placement="outside"/><text:Fill color="#FFFFFF"/>'),
        "ident-sub-style": ("ident-sub", "jp-bold", f'<text:Stroke color="#000000" width="6" placement="outside"/><text:Fill color="{c["theme_accent"]}"/>'),
        "card-number-style": ("card-number", "jp-bold", f'<text:Fill color="{c["card_label"]}"/>'),
        "card-title-style": ("card-title", "jp-black", f'<text:Fill color="{c["card_title"]}"/>'),
        "credits-style": ("credits", "jp-bold", '<text:Stroke color="#000000" width="5" placement="outside"/><text:Fill color="#FFFFFF"/>'),
        "credits-head-style": ("credits-head", "jp-black", f'<text:Stroke color="#000000" width="5" placement="outside"/><text:Fill color="{c["theme_accent"]}"/>'),
        "ending-style": ("ending", "jp-black", '<text:Fill color="#FFFFFF"/>'),
    }
    for sid_, (recipe, font, paint) in styles.items():
        w(f'  <text:Style id="{sid_}" recipe={{look.text.{recipe}}} font={{{font}}}>{paint}</text:Style>')
    w('  <text:Motion id="text-fade"><text:ItemKeyframe at="0" opacity="0"/><text:ItemKeyframe at="12" opacity="1"/></text:Motion>')

    tracks = ["picture.visual", "mix.audio"]

    def flow(fid, frame, style, during, body, z=60, align="start", block="center", motion=True, extra=""):
        m = " motion={text-fade}" if motion else ""
        w(f'  <text:Flow id="{fid}" timeline={{film.timeline}} within={{{frame}}} style={{{style}}} z="{z}" align="{align}" block-align="{block}" during={{{during}}}{m}{extra}>{body}</text:Flow>')
        tracks.append(f"{fid}.visual")

    logo_body = f'<text:P>{xml_escape(ch["logo"]["lines"][0])}<text:Break/>{xml_escape(ch["logo"]["lines"][1])}</text:P>'
    theme = ep["theme"]
    bodies = ([f"body-{opening['id']}"] if opening else []) + [f"body-{s['id']}" for s in chapters]
    if credits:
        bodies.append("credits")
    hug = ' inline-size="hug" block-size="hug"'
    for b in bodies:
        flow(f"logo-{b}", "logo-frame", "logo-style", f"film.{b}", logo_body, z=80, align="center", motion=False, extra=hug)
        flow(f"logo-sub-{b}", "logo-sub-frame", "logo-sub-style", f"film.{b}", xml_escape(ch["logo"]["sub"]), z=80, align="center", motion=False)
    for s in chapters:
        b = f"body-{s['id']}"
        flow(f"theme-main-{s['id']}", "theme-main-frame", "theme-main-style", f"film.{b}", xml_escape(theme["main"]))
        flow(f"theme-sub-{s['id']}", "theme-sub-frame", "theme-sub-style", f"film.{b}", xml_escape(theme["sub"]))
        flow(f"card-num-{s['id']}", "card-number-frame", "card-number-style", f"film.card-{s['id']}",
             f'{xml_escape(ch["chapter_label"])} {chapter_no[s["id"]]:02d}', align="center", block="end")
        flow(f"card-title-{s['id']}", "card-title-frame", "card-title-style", f"film.card-{s['id']}",
             xml_escape(s["title"]), align="center", block="start")
    if part["ident"]:
        flow("ident-logo", "ident-logo-frame", "ident-logo-style", "film.ident", logo_body, z=70, align="center", extra=hug)
        flow("ident-title", "ident-title-frame", "ident-title-style", "film.ident", xml_escape(theme["main"]), z=70, align="center")
        flow("ident-sub", "ident-sub-frame", "ident-sub-style", "film.ident", xml_escape(theme["sub"]), z=70, align="center")

    if credits:
        paras = [("head", "参考資料")] + [("body", s) for s in credits.get("sources", [])]
        paras += [("head", "　"), ("body", ch["texts"]["disclaimer"]), ("head", "　"), ("head", f'制作　{ch["name"]}')]
        # One paragraph with Breaks: separate <text:P> elements currently collide on run ids.
        runs = [f"<text:Span style={{credits-head-style}}>{xml_escape(t)}</text:Span>" if k == "head" else xml_escape(t)
                for k, t in paras]
        body = "<text:P>" + "<text:Break/>".join(runs) + "</text:P>"
        total_f = credits_duration(ep) * FPS
        est_h = int((len(credits.get("sources", [])) + 14) * 34 * 1.7)
        w(f'  <text:Motion id="credits-roll"><text:ItemKeyframe at="0" y="{H}"/><text:ItemKeyframe at="{total_f}" y="-{est_h}"/></text:Motion>')
        w(f'  <text:Flow id="credits-text" timeline={{film.timeline}} within={{credits-frame}} style={{credits-style}} z="950" align="center" block-align="start" during={{film.credits}} motion={{credits-roll}} block-size="hug">{body}</text:Flow>')
        tracks.append("credits-text.visual")
    if closing:
        end = ch["texts"]["end_card"]
        flow("ending-text", "ending-frame", "ending-style", "film.endcard",
             f"<text:P>{xml_escape(end[0])}<text:Break/>{xml_escape(end[1])}</text:P>", align="center")

    # ---- Captions -----------------------------------------------------------------------------
    w('  <caption-fine:Style id="caption-style" recipe={look.caption.primary} font={jp-black}/>')
    w('  <narrative-caption:Timing id="caption-timing" document={story.caption} binding={story.caption-binding} projection={story-time}/>')
    w('  <caption-fine:Caption id="captions" document={story.caption} timing={caption-timing} timeline={film.timeline} within={canvas.bounds}>')
    w('    <caption-fine:Use style={caption-style}/>')
    w("  </caption-fine:Caption>")
    tracks.append("captions.visual")

    # ---- Film ---------------------------------------------------------------------------------
    w('  <film:Film id="main" canvas={canvas.canvas} timeline={film.timeline} appearance={look.film.main}>')
    for t in tracks:
        w(f"    <film:Track source={{{t}}}/>")
    w("  </film:Film>")
    w('  <html:Video id="final" composition={main.composition} timeline={film.timeline}/>')
    w("</svml>")
    return "\n".join(out) + "\n"


def build(slug: str) -> list[dict]:
    ep = load_episode(slug)
    d = episode_dir(slug)
    parts = plan_parts(ep)
    chapter_no = {s["id"]: n for n, s in enumerate((s for s in ep["segments"] if s.get("kind") == "chapter"), 1)}

    hashes = segment_hashes(ep, d)
    (d / "out").mkdir(exist_ok=True)
    (d / "out" / "align-pending.json").write_text(json.dumps(hashes, indent=1), encoding="utf-8")
    cache_p = d / "out" / "align-cache.json"
    cache = json.loads(cache_p.read_text()) if cache_p.exists() else {}

    for stale in list(d.glob("episode.svml")) + list(d.glob("episode.svrun")) + list(d.glob("episode-p*.sv*")):
        stale.unlink()
    listing, reused = [], []
    for part in parts:
        svml = render_part(ep, d, part, chapter_no)
        (d / f"episode-{part['name']}.svml").write_text(svml, encoding="utf-8")
        run = ['<?svml using="@hypit/markup/run@1"?>', "", '<svrun version="1">',
               f'  <author source="./episode-{part["name"]}.svml"/>', '  <target output="final.video"/>']
        for seg in part["segs"]:
            sid = seg["id"]
            prev = cache.get(sid)
            if not prev or prev["hash"] != hashes[sid]:
                continue
            reused.append(sid)
            for name in (f"{sid}-media.media", f"{sid}-media.domain", f"{sid}-media.extent", f"{sid}-align.alignment"):
                cid = "kept-" + name.replace(".", "-")
                run.append(f'  <build-record id="{cid}" build="{prev["build"]}" output="{name}"/>')
                run.append(f'  <satisfy output="{name}" candidate="{cid}"/>')
        run.append("</svrun>")
        (d / f"episode-{part['name']}.svrun").write_text("\n".join(run) + "\n", encoding="utf-8")
        # a fingerprint of everything that changes this part's picture or sound
        fp = hashlib.sha256(svml.encode())
        for seg in part["segs"]:
            fp.update(hashes[seg["id"]].encode())
            for b in seg["blocks"]:
                img = d / "assets" / "derived" / "img" / f"{b['image']}.jpg"
                fp.update(img.read_bytes() if img.exists() else b"")
        listing.append({"name": part["name"], "svrun": f"episode-{part['name']}.svrun",
                        "segments": [s["id"] for s in part["segs"]], "fingerprint": fp.hexdigest()})
    (d / "out" / "parts.json").write_text(json.dumps(listing, indent=1), encoding="utf-8")
    if reused:
        print("reusing alignment for: " + ", ".join(reused))
    return listing


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    for p in build(sys.argv[1]):
        print(p["name"], p["svrun"], ",".join(p["segments"]))
